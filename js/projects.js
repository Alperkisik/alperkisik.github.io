const createProjects = (filter = "all") => {
    const container = document.getElementById("projectsGrid");
    const visibleProjects = sortDataByQuarterYear(projects.filter(portfolioFilters[filter]));
    const featuredProjects = visibleProjects.filter((project) => project.featured === true);
    const otherProjects = visibleProjects.filter((project) => project.featured !== true);

    let html = "";

    if (featuredProjects.length > 0)
        html += `<div class="featured-projects">${featuredProjects.map(featuredProjectHtml).join("")}</div>`;

    if (otherProjects.length > 0)
        html += `
      <div class="other-projects">
        <h3>Other Projects</h3>
        <table class="projects-table">
          <thead>
            <tr>
              <th class="col-year">Year</th>
              <th class="col-project">Project</th>
              <th class="col-owner">Made at</th>
              <th class="col-features">Core Features</th>
              <th class="col-links">Links</th>
            </tr>
          </thead>
          <tbody>${otherProjects.map(otherProjectRowHtml).join("")}</tbody>
        </table>
      </div>`;

    container.innerHTML = html;
};

const setupClickEvent = () => {
    const listItems = document.querySelectorAll(".sorting-list li");

    listItems.forEach((item) => {
        item.addEventListener("click", function () {
            if (this.classList.contains("active") === true) {
                return;
            }

            listItems.forEach((li) => {
                li.classList.remove("active");
            });

            this.classList.add("active");
            createProjects(this.getAttribute("data-p"));
        });
    });
};

const createGalleryBlock = (images, galleryName) => {
    const imageGallery = document.createElement("div");
    imageGallery.classList = "gallery";

    images.forEach((imageSrc) => {
        const img = document.createElement("img");
        img.src = imageSrc;
        img.loading = "lazy";
        img.alt = "";

        const link = document.createElement("a");
        link.href = imageSrc;
        link.setAttribute("data-pswp-width", "1600");
        link.setAttribute("data-pswp-height", "900");
        link.append(img);

        img.addEventListener("load", () => {
            link.setAttribute("data-pswp-width", img.naturalWidth);
            link.setAttribute("data-pswp-height", img.naturalHeight);
        }, { once: true });

        imageGallery.append(link);
    });

    return imageGallery;
};

const setupGallery = (project) => {
    const container = document.getElementById("project-img-gallery");

    if (project.imageGallery === null || project.imageGallery === undefined) {
        container.remove();
        return;
    }

    const isFlatList = project.imageGallery.every((item) => typeof item === "string");
    const groups = isFlatList
        ? [{ title: "", images: project.imageGallery }]
        : project.imageGallery;

    groups.forEach((group) => {
        if (group.title) {
            const heading = document.createElement("h3");
            heading.classList = "theme-title-3 color-blue mt-4 mb-3";
            heading.innerHTML = group.title;

            container.append(heading);
        }

        container.append(createGalleryBlock(group.images, group.title || "gallery"));
    });

};

